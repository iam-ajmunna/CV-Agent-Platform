"""cv_agent.experiments.interfaces — Authoritative contracts for ADR-0004 Experiment Ledger.

Defines:
- ExperimentStatus and WorkloadType enums.
- ExecutionTarget enum (local_gpu, remote_gpu, cloud).
- AccuracyMetrics and SystemMetrics dataclasses.
- ArtifactManifest dataclass.
- ExperimentSpec: complete immutable initialization specification.
- ExperimentRecord: complete state record distinguishing immutable facts from lifecycle fields.
- ExperimentLedger protocol.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from enum import Enum
from typing import Any, Protocol


class ExperimentStatus(str, Enum):
    """Lifecycle status of an experiment run [P§25]."""

    PROPOSED = "proposed"
    QUEUED = "queued"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class WorkloadType(str, Enum):
    """Category of experimental workload per ADR-0004 §2.4.C."""

    TRAINING = "training"
    EVALUATION = "evaluation"
    OPTIMIZATION = "optimization"
    BENCHMARK = "benchmark"


class ExecutionTarget(str, Enum):
    """Execution environment per ADR-0004 §2.4.D and Q2 / D-014."""

    LOCAL_GPU = "local_gpu"
    REMOTE_GPU = "remote_gpu"
    CLOUD = "cloud"


@dataclass(frozen=True)
class AccuracyMetrics:
    """Standardized computer-vision evaluation accuracy metrics [P§12]."""

    map_50: float | None = None
    map_50_95: float | None = None
    precision: float | None = None
    recall: float | None = None
    f1_score: float | None = None
    additional_metrics: Mapping[str, float] | None = None


@dataclass(frozen=True)
class SystemMetrics:
    """Hardware and execution system performance metrics [P§12], [P§29.4]."""

    peak_vram_mb: float | None = None
    peak_ram_mb: float | None = None
    gpu_hours: float | None = None
    training_time_seconds: float | None = None
    latency_e2e_ms: float | None = None
    latency_inference_ms: float | None = None
    throughput_fps: float | None = None
    power_draw_watts: float | None = None


@dataclass(frozen=True)
class ArtifactManifest:
    """Output artifacts generated by an experiment run."""

    weights_uri: str | None = None
    engine_uri: str | None = None
    plots_uri: str | None = None
    failure_analysis_ref: str | None = None
    checksums: Mapping[str, str] | None = None


@dataclass(frozen=True)
class ExperimentSpec:
    """Immutable specification required to initialize an experiment run [P§25].

    Enforces complete reproducibility metadata per PM review finding 2 & 3.
    """

    name: str
    hypothesis: str
    workload_type: WorkloadType
    target: ExecutionTarget
    model_name: str
    model_variant: str
    commit_sha: str
    dataset_version: str
    seed: int
    batch_size: int
    input_resolution: tuple[int, int]
    precision: str
    config_uri: str
    config_hash: str
    hyperparameters: Mapping[str, Any]
    parent_exp_id: str | None = None
    baseline_id: str | None = None
    approval_ref: str | None = None
    accuracy_metric_requirements: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if isinstance(self.accuracy_metric_requirements, (list, tuple)):
            reqs = tuple(self.accuracy_metric_requirements)
        elif self.accuracy_metric_requirements is None:
            reqs = ()
        else:
            reqs = tuple(self.accuracy_metric_requirements)

        # Default for training workload if unspecified
        if self.workload_type == WorkloadType.TRAINING and not reqs:
            reqs = ("map_50", "map_50_95", "precision", "recall")

        object.__setattr__(self, "accuracy_metric_requirements", reqs)


@dataclass(frozen=True)
class ExperimentRecord:
    """Complete experiment record distinguishing immutable facts from lifecycle state.

    Once status is terminal (completed, failed, cancelled), the record is strictly frozen [P§25].
    """

    exp_id: str
    spec: ExperimentSpec
    status: ExperimentStatus
    created_at: str
    started_at: str | None
    completed_at: str | None
    job_id: str | None
    accuracy_metrics: AccuracyMetrics | None
    system_metrics: SystemMetrics | None
    artifacts: ArtifactManifest | None
    error_message: str | None
    notes: str | None

    @property
    def is_terminal(self) -> bool:
        """Returns True if the experiment lifecycle is terminal and immutable."""
        return self.status in (
            ExperimentStatus.COMPLETED,
            ExperimentStatus.FAILED,
            ExperimentStatus.CANCELLED,
        )


class ExperimentLedger(Protocol):
    """Append-oriented queryable interface to .cv_agent/state/experiments.sqlite."""

    def create_experiment(self, spec: ExperimentSpec) -> ExperimentRecord:
        """Create a new experiment run in PROPOSED status."""
        ...

    def transition_status(
        self,
        exp_id: str,
        new_status: ExperimentStatus,
        job_id: str | None = None,
        error_message: str | None = None,
    ) -> ExperimentRecord:
        """Transition experiment lifecycle status per the transition matrix."""
        ...

    def complete_experiment(
        self,
        exp_id: str,
        accuracy: AccuracyMetrics,
        system: SystemMetrics,
        artifacts: ArtifactManifest,
        notes: str | None = None,
    ) -> ExperimentRecord:
        """Atomically record results and mark experiment as COMPLETED (immutable thereafter)."""
        ...

    def fail_experiment(self, exp_id: str, error_message: str) -> ExperimentRecord:
        """Mark an experiment as FAILED with diagnostic error message (immutable thereafter)."""
        ...

    def cancel_experiment(self, exp_id: str, reason: str) -> ExperimentRecord:
        """Mark an experiment as CANCELLED with explanation (immutable thereafter)."""
        ...

    def get_experiment(self, exp_id: str) -> ExperimentRecord | None:
        """Retrieve a single experiment record by ID."""
        ...

    def get_baseline(
        self, workload_type: WorkloadType | None = None
    ) -> ExperimentRecord | None:
        """Retrieve the designated active baseline record for the specified workload [P§29.2]."""
        ...

    def set_active_baseline(self, exp_id: str, workload_type: WorkloadType) -> None:
        """Designate an experiment as the active baseline for a workload class.

        Precondition: exp_id must reference an existing completed experiment
        whose workload_type matches the designated workload class.
        """
        ...

    def list_experiments(
        self,
        status: ExperimentStatus | None = None,
        workload_type: WorkloadType | None = None,
        model_name: str | None = None,
        dataset_version: str | None = None,
    ) -> tuple[ExperimentRecord, ...]:
        """Query experiment runs matching specified filter criteria."""
        ...
